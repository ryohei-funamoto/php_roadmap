<?php

// echo: 言語構造（関数ではない）。かっこは不要で、カンマ区切りで複数の値を出力できる
echo "Hello", ", ", "World", "\n";
echo("かっこ付きでも書ける\n");

// print: これも言語構造。引数は1つだけで、常に 1 を返す
print "print は引数を1つだけ受け取る\n";
// print "a", "b";  // ← 構文エラーになる

// print は値を返すので、式の中で使える（echo は使えない）
$result = print "戻り値を確認: ";
echo $result, "\n";   // 1

// 実用上の違いはほぼ無いので、一般的には echo を使う
